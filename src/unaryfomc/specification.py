"""Finite labeled specifications extracted from compiled C1F sentences."""

from __future__ import annotations

from dataclasses import dataclass
from math import exp
from typing import Dict, FrozenSet, Sequence, Tuple


FloatMatrix = Tuple[Tuple[float, ...], ...]
LocalState = Tuple[int, ...]
LocalDistribution = Dict[LocalState, float]


def _identity_matrix(size: int) -> FloatMatrix:
    return tuple(
        tuple(1.0 if row == column else 0.0 for column in range(size))
        for row in range(size)
    )


def _matrix_multiply(left: FloatMatrix, right: FloatMatrix) -> FloatMatrix:
    size = len(left)
    if len(right) != size:
        raise ValueError("Matrix dimensions do not agree")
    return tuple(
        tuple(
            sum(left[row][middle] * right[middle][column] for middle in range(size))
            for column in range(size)
        )
        for row in range(size)
    )


def _matrix_power(matrix: FloatMatrix, exponent: int) -> FloatMatrix:
    if exponent < 0:
        raise ValueError("Matrix exponent must be non-negative")
    result = _identity_matrix(len(matrix))
    factor = matrix
    remaining = exponent
    while remaining:
        if remaining & 1:
            result = _matrix_multiply(result, factor)
        remaining >>= 1
        if remaining:
            factor = _matrix_multiply(factor, factor)
    return result


def _matrix_trace(matrix: FloatMatrix) -> float:
    return sum(matrix[index][index] for index in range(len(matrix)))


def _matrix_determinant(matrix: FloatMatrix) -> float:
    size = len(matrix)
    if size == 0:
        return 1.0
    work = [list(row) for row in matrix]
    determinant = 1.0
    for column in range(size):
        pivot_row = max(range(column, size), key=lambda row: abs(work[row][column]))
        pivot = work[pivot_row][column]
        if pivot == 0.0:
            return 0.0
        if pivot_row != column:
            work[column], work[pivot_row] = work[pivot_row], work[column]
            determinant = -determinant
        pivot = work[column][column]
        determinant *= pivot
        for row in range(column + 1, size):
            factor = work[row][column] / pivot
            for trailing_column in range(column + 1, size):
                work[row][trailing_column] -= factor * work[column][trailing_column]
    return determinant


def _capped_add(
    left: LocalState,
    right: LocalState,
    caps: LocalState,
) -> LocalState:
    return tuple(
        min(cap, left_value + right_value)
        for cap, left_value, right_value in zip(caps, left, right)
    )


def _reachable_states(
    contributions: Sequence[LocalState],
    caps: LocalState,
) -> FrozenSet[LocalState]:
    """Return the capped submonoid generated by ``contributions``."""

    zero = tuple(0 for _ in caps)
    reached = {zero}
    pending = [zero]
    for state in pending:
        for contribution in contributions:
            updated = _capped_add(state, contribution, caps)
            if updated not in reached:
                reached.add(updated)
                pending.append(updated)
    return frozenset(reached)


def _distribution_multiply(
    left: LocalDistribution,
    right: LocalDistribution,
    caps: LocalState,
) -> LocalDistribution:
    result: LocalDistribution = {}
    for left_state, left_value in left.items():
        for right_state, right_value in right.items():
            state = _capped_add(left_state, right_state, caps)
            result[state] = result.get(state, 0.0) + left_value * right_value
    return result


def _capped_exponential_factor(
    value: float,
    contribution: LocalState,
    caps: LocalState,
) -> LocalDistribution:
    """Evaluate ``exp(value * Z**contribution)`` in the capped monoid."""

    zero = tuple(0 for _ in caps)
    if not any(contribution):
        return {zero: exp(value)}

    saturation_count = max(
        (cap + increment - 1) // increment
        for cap, increment in zip(caps, contribution)
        if increment
    )
    result: LocalDistribution = {}
    term = 1.0
    partial_sum = 0.0
    for count in range(saturation_count):
        state = tuple(
            min(cap, count * increment)
            for cap, increment in zip(caps, contribution)
        )
        result[state] = result.get(state, 0.0) + term
        partial_sum += term
        term *= value / (count + 1)

    saturated = tuple(
        cap if increment else 0
        for cap, increment in zip(caps, contribution)
    )
    tail = exp(value) - partial_sum
    # Cancellation can make a tiny positive exponential tail slightly negative.
    if tail < 0.0 and abs(tail) <= 1e-14 * max(1.0, exp(value)):
        tail = 0.0
    result[saturated] = result.get(saturated, 0.0) + tail
    return result


@dataclass(frozen=True)
class C1FLabeledSpecification:
    """Finite EGF system for the monadic labeled model class.

    ``successor[p][q]`` records that profile ``p`` may point to profile ``q``.
    The tree variables are indexed by ``transient_profiles``.  The remaining
    profiles occur only on cycles whose lengths are visible to the sentence.
    """

    depth: int
    successor: Tuple[Tuple[bool, ...], ...]
    multiplicities: Tuple[int, ...]
    visible_cycle_lengths: Tuple[int | None, ...]
    transient_profiles: Tuple[int, ...]
    eventual_start: int = 0
    long_cycle_profiles: Tuple[int, ...] | None = None
    local_caps: LocalState = tuple()
    local_contributions: Tuple[LocalState, ...] = tuple()
    local_acceptance: Tuple[FrozenSet[LocalState], ...] = tuple()

    def __post_init__(self) -> None:
        profile_count = len(self.successor)
        if any(len(row) != profile_count for row in self.successor):
            raise ValueError("The successor matrix must be square")
        if len(self.multiplicities) != profile_count:
            raise ValueError("Profile multiplicities do not match the successor matrix")
        if len(self.visible_cycle_lengths) != profile_count:
            raise ValueError("Visible cycle data do not match the successor matrix")
        if any(multiplicity <= 0 for multiplicity in self.multiplicities):
            raise ValueError("Profile multiplicities must be positive")
        if any(profile < 0 or profile >= profile_count for profile in self.transient_profiles):
            raise ValueError("Transient profile index is out of range")
        long_cycle_profiles = self._long_cycle_profiles()
        if any(profile < 0 or profile >= profile_count for profile in long_cycle_profiles):
            raise ValueError("Long-cycle profile index is out of range")
        if any(cap <= 0 for cap in self.local_caps):
            raise ValueError("Local predecessor caps must be positive")
        if self.local_contributions:
            if len(self.local_contributions) != profile_count:
                raise ValueError("Local contributions do not match the profile count")
            if any(
                len(contribution) != len(self.local_caps)
                for contribution in self.local_contributions
            ):
                raise ValueError("Local contribution dimensions do not match their caps")
            if any(
                increment < 0
                for contribution in self.local_contributions
                for increment in contribution
            ):
                raise ValueError("Local contributions must be non-negative")
        elif self.local_caps:
            raise ValueError("Guarded specifications require local contributions")
        if self.local_acceptance:
            if len(self.local_acceptance) != profile_count:
                raise ValueError("Local acceptance sets do not match the profile count")
            for states in self.local_acceptance:
                for state in states:
                    if len(state) != len(self.local_caps) or any(
                        value < 0 or value > cap
                        for value, cap in zip(state, self.local_caps)
                    ):
                        raise ValueError("Invalid capped local acceptance state")
        elif self.local_caps:
            raise ValueError("Guarded specifications require local acceptance sets")

    @property
    def profile_count(self) -> int:
        return len(self.successor)

    @property
    def tree_dimension(self) -> int:
        return len(self.transient_profiles)

    @property
    def cycle_dimension(self) -> int:
        return len(self._long_cycle_profiles())

    @property
    def has_guarded_predecessors(self) -> bool:
        return bool(self.local_caps)

    def _long_cycle_profiles(self) -> Tuple[int, ...]:
        if self.long_cycle_profiles is None:
            return self.transient_profiles
        return self.long_cycle_profiles

    def _local_contribution(self, profile: int) -> LocalState:
        if not self.local_contributions:
            return tuple()
        return self.local_contributions[profile]

    def _accepted_states(self, profile: int) -> FrozenSet[LocalState]:
        if not self.local_acceptance:
            return frozenset((tuple(),))
        return self.local_acceptance[profile]

    def _child_distribution(
        self,
        root_profile: int,
        trees: Sequence[float],
    ) -> LocalDistribution:
        grouped: Dict[LocalState, float] = {}
        for child_index, child_profile in enumerate(self.transient_profiles):
            if not self.successor[child_profile][root_profile]:
                continue
            contribution = self._local_contribution(child_profile)
            grouped[contribution] = grouped.get(contribution, 0.0) + trees[child_index]

        zero = tuple(0 for _ in self.local_caps)
        distribution: LocalDistribution = {zero: 1.0}
        for contribution, value in grouped.items():
            distribution = _distribution_multiply(
                distribution,
                _capped_exponential_factor(
                    value,
                    contribution,
                    self.local_caps,
                ),
                self.local_caps,
            )
        return distribution

    def _projected_child_value(
        self,
        root_profile: int,
        distribution: LocalDistribution,
        extra: LocalState | None = None,
    ) -> float:
        accepted = self._accepted_states(root_profile)
        if extra is None:
            return sum(
                value
                for state, value in distribution.items()
                if state in accepted
            )
        return sum(
            value
            for state, value in distribution.items()
            if _capped_add(state, extra, self.local_caps) in accepted
        )

    def dependency_matrix(self) -> Tuple[Tuple[bool, ...], ...]:
        """Return the Jacobian support of the rooted-tree system."""

        dimension = self.tree_dimension
        if dimension == 0:
            return tuple()
        jacobian = self.tree_jacobian(1.0, tuple(1.0 for _ in range(dimension)))
        return tuple(
            tuple(value > 0.0 for value in row)
            for row in jacobian
        )

    def cycle_transfers_are_tree_independent(self) -> bool:
        """Decide exactly whether every cycle transfer ignores all trees.

        The transfer series have non-negative coefficients.  An entry depends
        on a tree coordinate exactly when an accepted predecessor multiset can
        contain one distinguished productive child of that type.  This finite
        reachability test avoids using a numerical residual for a structural
        property.
        """

        if self.tree_dimension == 0:
            return True
        profile_sets = [self._long_cycle_profiles()]
        profile_sets.extend(
            tuple(
                profile
                for profile, visible_length in enumerate(
                    self.visible_cycle_lengths
                )
                if visible_length == cycle_length
            )
            for cycle_length in range(1, self.depth + 1)
        )
        for active_profiles in profile_sets:
            for previous in active_profiles:
                for current in active_profiles:
                    if not self.successor[previous][current]:
                        continue
                    child_profiles = tuple(
                        child
                        for child in self.transient_profiles
                        if self.successor[child][current]
                    )
                    if not child_profiles:
                        continue
                    reachable = _reachable_states(
                        tuple(self._local_contribution(child) for child in child_profiles),
                        self.local_caps,
                    )
                    cycle_contribution = self._local_contribution(previous)
                    for child in child_profiles:
                        distinguished = _capped_add(
                            cycle_contribution,
                            self._local_contribution(child),
                            self.local_caps,
                        )
                        if any(
                            _capped_add(state, distinguished, self.local_caps)
                            in self._accepted_states(current)
                            for state in reachable
                        ):
                            return False
        return True

    def _check_trees(self, trees: Sequence[float]) -> None:
        if len(trees) != self.tree_dimension:
            raise ValueError(
                f"Expected {self.tree_dimension} tree values, received {len(trees)}"
            )

    def tree_rhs(self, x: float, trees: Sequence[float]) -> Tuple[float, ...]:
        """Evaluate ``Phi(x, T)`` in the system ``T = Phi(x, T)``."""

        self._check_trees(trees)
        return tuple(
            x
            * self.multiplicities[root_profile]
            * self._projected_child_value(
                root_profile,
                self._child_distribution(root_profile, trees),
            )
            for root_profile in self.transient_profiles
        )

    def tree_jacobian(self, x: float, trees: Sequence[float]) -> FloatMatrix:
        """Evaluate the Jacobian ``Phi_T(x, T)``."""

        self._check_trees(trees)
        distributions = tuple(
            self._child_distribution(root_profile, trees)
            for root_profile in self.transient_profiles
        )
        return tuple(
            tuple(
                0.0
                if not self.successor[child_profile][root_profile]
                else x
                * self.multiplicities[root_profile]
                * self._projected_child_value(
                    root_profile,
                    distributions[row],
                    self._local_contribution(child_profile),
                )
                for child_profile in self.transient_profiles
            )
            for row, root_profile in enumerate(self.transient_profiles)
        )

    def tree_x_derivative(self, x: float, trees: Sequence[float]) -> Tuple[float, ...]:
        """Evaluate the partial derivative ``Phi_x(x, T)``."""

        self._check_trees(trees)
        if x != 0.0:
            return tuple(value / x for value in self.tree_rhs(x, trees))
        return tuple(
            self.multiplicities[root_profile]
            * self._projected_child_value(
                root_profile,
                self._child_distribution(root_profile, trees),
            )
            for root_profile in self.transient_profiles
        )

    def tree_hessian_direction(
        self,
        x: float,
        trees: Sequence[float],
        direction: Sequence[float],
    ) -> Tuple[float, ...]:
        """Evaluate the vector ``Phi_TT(x,T)[direction,direction]``."""

        self._check_trees(trees)
        self._check_trees(direction)
        result = []
        for root_profile in self.transient_profiles:
            distribution = self._child_distribution(root_profile, trees)
            pointed: Dict[LocalState, float] = {}
            for child_index, child_profile in enumerate(self.transient_profiles):
                if not self.successor[child_profile][root_profile]:
                    continue
                contribution = self._local_contribution(child_profile)
                pointed[contribution] = (
                    pointed.get(contribution, 0.0) + direction[child_index]
                )
            double_pointed = _distribution_multiply(
                pointed,
                pointed,
                self.local_caps,
            )
            value = sum(
                coefficient
                * self._projected_child_value(
                    root_profile,
                    distribution,
                    contribution,
                )
                for contribution, coefficient in double_pointed.items()
            )
            result.append(x * self.multiplicities[root_profile] * value)
        return tuple(result)

    def decorations(self, x: float, trees: Sequence[float]) -> Tuple[float, ...]:
        """Evaluate all cycle-vertex decorations ``U_q(x, T)``."""

        self._check_trees(trees)
        return tuple(
            x
            * self.multiplicities[root_profile]
            * self._projected_child_value(
                root_profile,
                self._child_distribution(root_profile, trees),
            )
            for root_profile in range(self.profile_count)
        )

    def cycle_matrix(
        self,
        active_profiles: Sequence[int],
        x: float,
        trees: Sequence[float],
    ) -> FloatMatrix:
        """Evaluate the transfer matrix on a selected set of cycle profiles."""

        self._check_trees(trees)
        distributions = {
            current: self._child_distribution(current, trees)
            for current in active_profiles
        }
        return tuple(
            tuple(
                0.0
                if not self.successor[previous][current]
                else x
                * self.multiplicities[current]
                * self._projected_child_value(
                    current,
                    distributions[current],
                    self._local_contribution(previous),
                )
                for current in active_profiles
            )
            for previous in active_profiles
        )

    def long_cycle_matrix(self, x: float, trees: Sequence[float]) -> FloatMatrix:
        return self.cycle_matrix(self._long_cycle_profiles(), x, trees)

    def jacobian_transfer_residual(
        self,
        x: float,
        trees: Sequence[float],
    ) -> float:
        """Return the residual in ``D = Phi_T**T`` on productive types."""

        long_profiles = self._long_cycle_profiles()
        long_positions = {
            profile: position
            for position, profile in enumerate(long_profiles)
        }
        if any(profile not in long_positions for profile in self.transient_profiles):
            return float("inf")
        jacobian = self.tree_jacobian(x, trees)
        transfer = self.long_cycle_matrix(x, trees)
        return max(
            (
                abs(
                    transfer[long_positions[child_profile]][
                        long_positions[root_profile]
                    ]
                    - jacobian[root_index][child_index]
                )
                for child_index, child_profile in enumerate(self.transient_profiles)
                for root_index, root_profile in enumerate(self.transient_profiles)
            ),
            default=0.0,
        )

    def long_cycle_determinant(self, x: float, trees: Sequence[float]) -> float:
        matrix = self.long_cycle_matrix(x, trees)
        identity_minus = tuple(
            tuple(
                (1.0 if row == column else 0.0) - matrix[row][column]
                for column in range(len(matrix))
            )
            for row in range(len(matrix))
        )
        return _matrix_determinant(identity_minus)

    def finite_cycle_correction(self, x: float, trees: Sequence[float]) -> float:
        """Evaluate the finite short-cycle correction ``H(x, T)``."""

        long_matrix = self.long_cycle_matrix(x, trees)
        correction = 0.0
        for cycle_length in range(1, self.depth + 1):
            visible_profiles = tuple(
                profile
                for profile, visible_length in enumerate(self.visible_cycle_lengths)
                if visible_length == cycle_length
            )
            visible_matrix = self.cycle_matrix(visible_profiles, x, trees)
            correction += (
                _matrix_trace(_matrix_power(visible_matrix, cycle_length))
                - _matrix_trace(_matrix_power(long_matrix, cycle_length))
            ) / cycle_length
        return correction

    def egf_numerator(self, x: float, trees: Sequence[float]) -> float:
        return exp(self.finite_cycle_correction(x, trees))

    def egf_value(self, x: float, trees: Sequence[float]) -> float:
        """Evaluate ``exp(H(x,T)) / det(I-B(x,T))`` off its singular set."""

        denominator = self.long_cycle_determinant(x, trees)
        if denominator == 0.0:
            raise ZeroDivisionError("The labeled EGF denominator vanishes")
        return self.egf_numerator(x, trees) / denominator
